import { chromium } from 'playwright';
const B = 'http://127.0.0.1:5173/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1088, height: 754 } });
const p = await ctx.newPage();
await p.addInitScript(() => localStorage.setItem('anywhere-data', JSON.stringify({ onboarded: true, profile: { roleId: 'designer' } })));
await p.goto(B, { waitUntil: 'networkidle' });
await p.waitForTimeout(600);
const box = async (sel) => {
  const el = p.locator(sel).first(); if (!(await el.count())) return null;
  const bb = await el.boundingBox(); if (!bb) return null;
  return { x: +bb.x.toFixed(1), y: +bb.y.toFixed(1), w: +bb.width.toFixed(1), h: +bb.height.toFixed(1), r: +(bb.x + bb.width).toFixed(1), b: +(bb.y + bb.height).toFixed(1) };
};
const rep = async (l, s) => console.log(l.padEnd(16), JSON.stringify(await box(s)));
await p.click('button[title="AI 伴侣"]'); await p.waitForTimeout(500);
await rep('companion', '.companion');
await rep('avatar', '.ai-avatar');
await rep('greet', '.ai-greet');
await rep('mode', '.ai-mode');
await rep('panel', '.chat-panel');
await rep('composer', '.composer');
await rep('bottom', '.bottom-actions');
await rep('btn1', '.bottom-actions button:nth-child(1)');
await rep('btn3', '.bottom-actions button:nth-child(3)');
const f = await p.locator('.ai-greet').first().evaluate((el) => { const c = getComputedStyle(el); return { fs: c.fontSize, fw: c.fontWeight, bg: c.backgroundImage, color: c.color }; });
console.log('greetFont', JSON.stringify(f));
await p.click('button[title="更多"]'); await p.waitForTimeout(500);
await rep('more-page', '.more-page');
await rep('more-cards', '.more-cards');
await rep('card1', '.big-card:nth-child(1)');
await rep('card2', '.big-card:nth-child(2)');
await p.click('button[title="聚合引擎"]'); await p.waitForTimeout(500);
await rep('engine-body', '.engine-body');
await rep('search-row', '.engine-body .search-row');
await rep('engine-grid', '.engine-grid');
await rep('etile1', '.engine-grid .site-tile:nth-child(1)');
await rep('etile2', '.engine-grid .site-tile:nth-child(2)');
await b.close();
